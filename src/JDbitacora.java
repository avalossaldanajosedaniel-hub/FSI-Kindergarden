    private void BActualizarbActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BActualizarbActionPerformed
         
    if (cnx == null || cnx.con == null) {
        JOptionPane.showMessageDialog(this,
                "No hay conexión con la base de datos.");
        return;
    }

    if (LFecha.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Primero selecciona la fecha con el botón HOY.");
        return;
    }

    if (CBInfantes.getSelectedItem() == null ||
        CBInfantes1.getSelectedItem() == null ||
        CBResponsables.getSelectedItem() == null ||
        CBEducador.getSelectedItem() == null ||
        CBTipo.getSelectedItem() == null) {

        JOptionPane.showMessageDialog(this,
                "Selecciona todos los datos requeridos.");
        return;
    }

    Bitacora bit = new Bitacora(
        null,
        LFecha.getText(),
        CBTipo.getSelectedItem().toString(),
        TXObservaciones.getText(),
        CBInfantes.getSelectedItem().toString(),
        CBInfantes1.getSelectedItem().toString(),
        CBResponsables.getSelectedItem().toString(),
        CBEducador.getSelectedItem().toString()
    );

    if (bit.actualiza(cnx.con) == 1) {
        JOptionPane.showMessageDialog(this,
                "Bitácora registrada correctamente.");
        this.dispose();
    } else {
        JOptionPane.showMessageDialog(this,
                "Error al registrar la bitácora. Revisa la consola.");
    }
    }//GEN-LAST:event_BActualizarbActionPerformed

