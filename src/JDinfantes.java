    private void BActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BActualizarActionPerformed
     SimpleDateFormat s = new SimpleDateFormat("yyyy-MM-dd");
    Infante kid = new Infante(
            Txcurp.getText(),
            Txnombre.getText(),
            CBsexo.getSelectedItem().toString(),
            s.format((Date)SPfecha.getValue()),
            CBEstado.getSelectedItem().toString()
    );
            
    if (kid.actualiza(cnx.con) == 1) {
        JOptionPane.showMessageDialog(this, "Datos del infante actualizado ");
        this.dispose();
    } else {
        JOptionPane.showMessageDialog(this, "Error al realizar el registro :(");
    }
        
    }//GEN-LAST:event_BActualizarActionPerformed

